"""Synthetic training data for provider risk prediction.

SYNTHETIC DATA NOTICE
---------------------
Every row is generated by the process below. These are not observations of any
real supplier, service centre or marketplace. Model scores computed from this
data describe how the model behaves on a controlled synthetic distribution and
must never be reported as industry performance.

What the model is for
---------------------
Target: `failed` - did this provider operation end in failure (or SLA breach)?

The label is deliberately *not* invented independently of the features. It is
generated from a latent risk function of provider characteristics plus noise, so
there is a real signal to learn and the ceiling on achievable accuracy is known
by construction. A model that scored 100% here would indicate leakage, not
success.

Why this is decision support, not a decision
--------------------------------------------
The prediction only ever adjusts the *score* of a provider that has already
passed every hard constraint. It cannot make an unauthorized service centre
eligible, cannot override a compatibility verdict, and cannot approve a
warranty claim. Those remain deterministic. See `engines/selection.py`, where
the ML score is applied after Phase 1 filtering, never before.
"""

from __future__ import annotations

import argparse
import math
import random
from pathlib import Path

FEATURES = [
    "historical_success_rate",
    "avg_latency_ms",
    "failure_count",
    "retry_count",
    "sla_violations",
    "available_capacity",
    "cost_index",
    "distance_km",
    "sla_hours",
    "operations_total",
    "provider_type_idx",
    "operation_type_idx",
    "is_urgent",
]

PROVIDER_TYPES = ["MARKETPLACE", "MANUFACTURER", "WARRANTY",
                  "SERVICE_CENTRE", "PARTS_SUPPLIER"]
OPERATION_TYPES = [
    "VERIFY_PURCHASE", "VERIFY_PRODUCT", "VERIFY_WARRANTY", "CHECK_COVERAGE",
    "CHECK_PART_AVAILABILITY", "RESERVE_PART", "BOOK_SERVICE", "UPDATE_REPAIR",
]


def _sigmoid(x: float) -> float:
    return 1.0 / (1.0 + math.exp(-max(-30.0, min(30.0, x))))


def generate_rows(n: int = 6000, seed: int = 7) -> list[dict]:
    rng = random.Random(seed)
    rows: list[dict] = []

    for _ in range(n):
        provider_type = rng.choice(PROVIDER_TYPES)
        operation_type = rng.choice(OPERATION_TYPES)

        # Providers come in rough quality tiers, which is what makes the
        # problem learnable rather than pure noise.
        tier = rng.choices(["strong", "average", "weak"], weights=[0.4, 0.4, 0.2])[0]
        if tier == "strong":
            success = rng.uniform(0.93, 0.995)
            latency = rng.uniform(80, 400)
            sla_violations = rng.randint(0, 2)
        elif tier == "average":
            success = rng.uniform(0.80, 0.93)
            latency = rng.uniform(300, 900)
            sla_violations = rng.randint(0, 6)
        else:
            success = rng.uniform(0.50, 0.80)
            latency = rng.uniform(700, 2500)
            sla_violations = rng.randint(3, 20)

        operations_total = rng.randint(20, 900)
        failure_count = int(operations_total * (1 - success))
        retry_count = int(failure_count * rng.uniform(0.6, 2.2))
        capacity = rng.randint(0, 20)
        cost_index = round(rng.uniform(0.55, 1.6), 3)
        distance_km = round(rng.uniform(1, 750), 1)
        sla_hours = rng.choice([12, 24, 36, 48, 72])
        is_urgent = 1 if rng.random() < 0.22 else 0

        # Latent risk. Coefficients chosen so that reliability dominates,
        # latency and SLA history matter, and cost/distance matter weakly -
        # which mirrors the weighting the deterministic selector uses.
        logit = (
            # Intercept tuned so failures are a genuine minority (~20-25%),
            # which is what makes accuracy a misleading metric here.
            -3.35
            + 5.20 * (1 - success)
            + 0.00055 * latency
            + 0.075 * sla_violations
            + 0.020 * retry_count / max(1, operations_total / 50)
            - 0.045 * capacity
            + 0.42 * cost_index
            + 0.00075 * distance_km
            + 0.009 * sla_hours
            + 0.38 * is_urgent
            + (0.45 if operation_type in {"RESERVE_PART", "BOOK_SERVICE"} else 0.0)
            + (0.25 if provider_type == "PARTS_SUPPLIER" else 0.0)
            + rng.gauss(0, 0.55)  # irreducible noise: caps achievable accuracy
        )
        failed = 1 if rng.random() < _sigmoid(logit) else 0

        rows.append({
            "historical_success_rate": round(success, 4),
            "avg_latency_ms": round(latency, 1),
            "failure_count": failure_count,
            "retry_count": retry_count,
            "sla_violations": sla_violations,
            "available_capacity": capacity,
            "cost_index": cost_index,
            "distance_km": distance_km,
            "sla_hours": sla_hours,
            "operations_total": operations_total,
            "provider_type": provider_type,
            "provider_type_idx": PROVIDER_TYPES.index(provider_type),
            "operation_type": operation_type,
            "operation_type_idx": OPERATION_TYPES.index(operation_type),
            "is_urgent": is_urgent,
            "failed": failed,
        })
    return rows


def write_csv(rows: list[dict], path: Path) -> None:
    import csv

    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate synthetic ML dataset")
    parser.add_argument("--rows", type=int, default=6000)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--out", default="artifacts/provider_operations.csv")
    args = parser.parse_args(argv)

    rows = generate_rows(args.rows, args.seed)
    write_csv(rows, Path(args.out))
    positives = sum(r["failed"] for r in rows)
    print(f"SYNTHETIC dataset written to {args.out}")
    print(f"  rows      : {len(rows)}")
    print(f"  failures  : {positives} ({positives / len(rows):.1%})")
    print(f"  features  : {len(FEATURES)}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
